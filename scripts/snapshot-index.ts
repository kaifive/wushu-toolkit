/**
 * Regenerate data/snapshots/index.ts: one lazy import per event, pointing at
 * that event's newest snapshot file. Run after adding snapshots.
 */
import { pathToFileURL } from "node:url";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { latestSnapshot } from "../lib/data/snapshot";

export function writeSnapshotIndex(root = join(process.cwd(), "data/snapshots")): string[] {
  const slugs = readdirSync(root).filter((d) => statSync(join(root, d)).isDirectory()).sort();
  const lines = slugs.flatMap((slug) => {
    const file = latestSnapshot(readdirSync(join(root, slug)));
    return file ? [`  "${slug}": { file: "${file}", load: () => import("./${slug}/${file}") },`] : [];
  });
  writeFileSync(
    join(root, "index.ts"),
    `// Generated by scripts/snapshot-index.ts. Do not edit by hand.\nimport type { SnapshotIndex } from "@/lib/data/snapshot";\n\nexport const SNAPSHOTS: SnapshotIndex = {\n${lines.join("\n")}\n};\n`,
  );
  return slugs;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  console.log("Indexed:", writeSnapshotIndex().join(", ") || "(none)");
}
